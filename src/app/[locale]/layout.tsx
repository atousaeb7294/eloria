import type { Metadata } from "next";
import type { ReactNode } from "react";

import "../globals.css";

import { hasLocale, NextIntlClientProvider } from "next-intl";

import {
  getTranslations,
  setRequestLocale,
  getMessages,
} from "next-intl/server";

import { notFound } from "next/navigation";
import { connection } from "next/server";

import { PageBackgroundProvider } from "@/components/page-background-provider";
import { DeferredSiteTools } from "@/components/deferred-site-tools";
import { SiteMeasurementTracker } from "@/components/site-measurement-tracker";
import { SiteStructuredData } from "@/components/site-structured-data";
import { PwaRegistration } from "@/components/pwa-registration";
import { MarketingAttributionTracker } from "@/components/marketing-attribution-tracker";
import { HomeNavigationReset } from "@/components/home-navigation-reset";

import { routing } from "@/i18n/routing";
import { siteBaseUrl } from "@/lib/site-url";
import { isSiteMeasurementEnabled } from "@/lib/site-measurement";

type LocaleParams = Promise<{
  locale: string;
}>;

type LocaleLayoutProps = Readonly<{
  children: ReactNode;
  params: LocaleParams;
}>;

export function generateStaticParams() {
  return routing.locales.map((locale) => ({
    locale,
  }));
}

export async function generateMetadata({
  params,
}: {
  params: LocaleParams;
}): Promise<Metadata> {
  const { locale } = await params;

  if (!hasLocale(routing.locales, locale)) {
    return {};
  }

  const t = await getTranslations({
    locale,
    namespace: "Metadata",
  });

  const baseUrl = siteBaseUrl();

  const title = t("title");
  const description = t("description");

  return {
    metadataBase: baseUrl,
    verification: process.env.GOOGLE_SITE_VERIFICATION
      ? { google: process.env.GOOGLE_SITE_VERIFICATION.trim() }
      : undefined,
    title,
    description,
    icons: {
      icon: [
        { url: "/favicon.ico", sizes: "48x48", type: "image/x-icon" },
        { url: "/icon.png", sizes: "64x64", type: "image/png" },
      ],
      apple: [{ url: "/apple-icon.png", sizes: "180x180", type: "image/png" }],
    },
    alternates: {
      canonical: `/${locale}`,
      languages: {
        fa: "/fa",
        en: "/en",
        "x-default": "/fa",
      },
    },

    openGraph: {
      type: "website",
      siteName: "ELORIA",
      locale: locale === "fa" ? "fa_IR" : "en_US",
      alternateLocale: locale === "fa" ? ["en_US"] : ["fa_IR"],
      title,
      description,
      url: `/${locale}`,
      images: [
        {
          url: "/images/hero/eloria-hero.webp",
          width: 1600,
          height: 900,
          alt: title,
        },
      ],
    },

    twitter: {
      card: "summary_large_image",
      title,
      description,
      images: ["/images/hero/eloria-hero.webp"],
    },
  };
}

export default async function LocaleLayout({
  children,
  params,
}: LocaleLayoutProps) {
  // The nonce generated by src/proxy.ts is request-specific. Waiting for the
  // connection makes every localized document render with the matching nonce
  // instead of serving a static document that could not safely use it.
  await connection();
  const { locale } = await params;

  if (!hasLocale(routing.locales, locale)) {
    notFound();
  }

  setRequestLocale(locale);

  const messages = await getMessages();

  return (
    <html
      data-scroll-behavior="smooth"
      lang={locale}
      dir={locale === "fa" ? "rtl" : "ltr"}
      suppressHydrationWarning
    >
      <body className="min-h-screen">
        <NextIntlClientProvider locale={locale} messages={messages}>
          <PageBackgroundProvider>
            <HomeNavigationReset />
            <SiteStructuredData />
            <PwaRegistration />
            <MarketingAttributionTracker />
            <SiteMeasurementTracker
              locale={locale}
              enabled={isSiteMeasurementEnabled()}
            />
            {children}
            <DeferredSiteTools locale={locale} />
          </PageBackgroundProvider>
        </NextIntlClientProvider>
      </body>
    </html>
  );
}
